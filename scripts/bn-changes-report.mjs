/**
 * Builds docs/localization/TRANSLATION_CHANGES.md from the change ledger
 * (docs/localization/translation-changes.jsonl written by apply-bn-patch.mjs).
 *
 * Hand-reviewed batches are listed in full (key, English, before, after, reason).
 * Rule-based batches are summarised with counts and examples; their full
 * before/after text is in the ledger.
 *
 * Usage: node scripts/bn-changes-report.mjs
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const dir = path.join(process.cwd(), "docs", "localization");
const rows = (await readFile(path.join(dir, "translation-changes.jsonl"), "utf8"))
  .trim()
  .split(/\r?\n/)
  .map((l) => JSON.parse(l));

const BATCHES = {
  "00-mechanical.json": ["Rule-based: spelling, punctuation and brand", "প্রকল্প → প্রজেক্ট, U+09F7 → ।, উত্পাদন → উৎপাদন, ইমেল → ইমেইল, Adon ERP → AdonERP, ASCII full stop → দাঁড়ি, stray spaces."],
  "01-layout-common.json": ["Navigation, footer and shared UI (hand-reviewed)", ""],
  "02-home.json": ["Home page (hand-reviewed)", "Hero typeWords intentionally untouched (owner-approved)."],
  "03-pricing.json": ["Pricing, Standard plan and Success Packs (hand-reviewed)", "Includes the 'Print quote' → 'print quota' mistranslation and removed invented claims."],
  "04-community-hubs.json": ["Community hub pages: Banglish rewritten (hand-reviewed)", ""],
  "05-community.json": ["Community pages, forum, blog, metadata (hand-reviewed)", ""],
  "06-cta-glossary.json": ["Rule-based: one approved string per recurring CTA / app name", "See style guide §3. Removed invented 'free' and 'AI/HR/architect expert' from CTAs."],
  "07-product-heroes.json": ["Product page metadata, heroes and CTAs (hand-reviewed)", ""],
  "20-as-a.json": ["Module showcases (/apps/*): machine translation rewritten, batch A", ""],
  "21-as-b.json": ["Module showcases: batch B", ""],
  "22-as-c.json": ["Module showcases: batch C", ""],
  "23-as-d.json": ["Module showcases: batch D", ""],
  "24-as-e.json": ["Module showcases: batch E", ""],
  "25-as-f.json": ["Module showcases: batch F", ""],
  "26-normalize.json": ["Rule-based: acronyms in Latin, spelling, story template", "এআই/সিআরএম/ইআরপি/পিওএস/এইচআর/এসএমএস → Latin; রিয়াল-টাইম → রিয়েল-টাইম; তাত্ক্ষণিক → তাৎক্ষণিক."],
  "27-ws.json": ["Whitespace parity", ""],
  "28-terms.json": ["Rule-based, context-aware terminology", "Applied only where the English string contains the term: Invoice → ইনভয়েস, Report → রিপোর্ট, Purchase/Sales/Production/Work Order → … অর্ডার."],
  "29-app-cards.json": ["Product page app cards and shared section headings (hand-reviewed)", ""],
  "30-inv.json": ["Split-headline duplication fix", ""],
};
const RULE_BASED = new Set(["00-mechanical.json", "06-cta-glossary.json", "26-normalize.json", "28-terms.json"]);

const cell = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\r?\n/g, " ⏎ ");
const byPatch = new Map();
for (const r of rows) {
  if (!byPatch.has(r.patch)) byPatch.set(r.patch, []);
  byPatch.get(r.patch).push(r);
}
const unique = new Set(rows.map((r) => r.key)).size;

let md = `# Bangla translation changes

Generated by \`node scripts/bn-changes-report.mjs\` from \`docs/localization/translation-changes.jsonl\`.

- Change records: **${rows.length}**
- Distinct keys changed: **${unique}** of 39,340 strings
- Source of truth: the JSONL ledger, one record per applied change: \`key\`, \`en\`, \`old\`, \`new\`, \`why\`, \`patch\`, \`at\`.

Some keys were touched by more than one batch, for example a rule-based fix followed by a hand rewrite. The ledger keeps every step in order.

## Summary by batch

| Batch | What | Changes |
|---|---|---|
${[...byPatch.entries()].map(([p, list]) => `| \`${p}\` | ${cell(BATCHES[p]?.[0] || p)} | ${list.length} |`).join("\n")}
`;

for (const [p, list] of byPatch) {
  const [title, note] = BATCHES[p] || [p, ""];
  md += `\n## ${title}\n\n`;
  if (note) md += `${note}\n\n`;
  const shown = RULE_BASED.has(p) ? list.slice(0, 15) : list;
  if (RULE_BASED.has(p)) md += `${list.length} changes. The first 15 are shown; the rest are in the ledger.\n\n`;
  md += `| Key | English | Before | After | Reason |\n|---|---|---|---|---|\n`;
  for (const r of shown) md += `| \`${cell(r.key)}\` | ${cell(r.en)} | ${cell(r.old)} | ${cell(r.new)} | ${cell(r.why)} |\n`;
}

await writeFile(path.join(dir, "TRANSLATION_CHANGES.md"), md, "utf8");
console.log(`wrote TRANSLATION_CHANGES.md (${rows.length} records, ${unique} keys)`);
